import { basename, dirname, relative } from "node:path";
import { behaviorIndexPath, fromProjectRoot, indexCssPath } from "./config.js";
import { readTextIfExists, writeText } from "./fs.js";
import type { LosetaConfig, Manifest, ManifestItem, Registry } from "./types.js";

const LAYER_ORDER =
  "loseta.tokens, loseta.reset, loseta.base, loseta.components, loseta.style, loseta.utilities";

function toPosix(path: string): string {
  return path.split("\\").join("/");
}

function importLine(target: string): string {
  return `@import "./${toPosix(target)}";`;
}

function orderedItems(manifest: Manifest, registry?: Registry): ManifestItem[] {
  const byName = new Map(manifest.items.map((item) => [item.name, item]));
  const ordered: ManifestItem[] = [];
  const seen = new Set<string>();

  for (const item of registry?.items ?? []) {
    const entry = byName.get(item.name);
    if (entry) {
      ordered.push(entry);
      seen.add(item.name);
    }
  }
  for (const entry of manifest.items) {
    if (!seen.has(entry.name)) ordered.push(entry);
  }
  return ordered;
}

function installedFiles(manifest: Manifest, registry?: Registry): string[] {
  const seen = new Set<string>();
  for (const item of orderedItems(manifest, registry)) {
    for (const file of item.files) {
      seen.add(file.path);
    }
  }
  return [...seen];
}

/** Generates the managed index.css for the installed files and style. */
export function generateIndex(
  manifest: Manifest,
  style: string,
  registry?: Registry
): string {
  const files = installedFiles(manifest, registry);
  const stylePrefix = `styles/${style}/`;
  const baseFiles = files.filter((file) => !file.startsWith("styles/"));
  const styleFiles = files.filter((file) => file.startsWith(stylePrefix));

  return [
    "/* Generated by loseta. Do not edit this file directly. */",
    `@layer ${LAYER_ORDER};`,
    "",
    ...baseFiles.map(importLine),
    "",
    ...styleFiles.map(importLine),
    ""
  ].join("\n");
}

/** Writes the generated index.css. */
export function writeIndex(
  projectRoot: string,
  config: LosetaConfig,
  manifest: Manifest,
  registry?: Registry
): void {
  writeText(
    indexCssPath(projectRoot, config),
    generateIndex(manifest, config.style, registry)
  );
}

/** Generates the managed behaviors/index.js for the installed entry modules. */
export function generateBehaviorIndex(entries: Iterable<string>): string {
  const targets = [...new Set(entries)].sort();
  const imports = targets.map(
    (target) => `import "./${toPosix(basename(target))}";`
  );

  return [
    "/* Generated by loseta. Do not edit this file directly. */",
    "",
    ...imports,
    ""
  ].join("\n");
}

/** Writes the generated behavior index when behavior modules are installed. */
export function writeBehaviorIndex(
  projectRoot: string,
  config: LosetaConfig,
  entries: Iterable<string>
): void {
  const targets = [...entries];
  if (targets.length === 0) return;
  writeText(behaviorIndexPath(projectRoot, config), generateBehaviorIndex(targets));
}

/**
 * Adds a single @import for loseta/index.css to the user's CSS entrypoint.
 * Returns true when the entrypoint was modified.
 */
export function addEntrypointImport(projectRoot: string, config: LosetaConfig): boolean {
  if (!config.entrypoint) return false;

  const entrypoint = fromProjectRoot(projectRoot, config.entrypoint);
  const index = indexCssPath(projectRoot, config);
  const existing = readTextIfExists(entrypoint);
  if (existing === undefined) return false;

  const importPath = toPosix(relative(dirname(entrypoint), index));
  const line = `@import "${importPath.startsWith(".") ? importPath : `./${importPath}`}";`;
  if (existing.includes(line)) return false;

  const lines = existing.split(/\r?\n/);
  let insertAt = 0;
  while (insertAt < lines.length && /^\s*@charset\b/.test(lines[insertAt] ?? "")) {
    insertAt += 1;
  }
  lines.splice(insertAt, 0, line);
  writeText(entrypoint, lines.join("\n"));
  return true;
}

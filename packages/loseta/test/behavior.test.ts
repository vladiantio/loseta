test("modified behavior files respect the conflict decision", async (t) => {
  const projectRoot = project();
  t.after(() => rmSync(projectRoot, { recursive: true, force: true }));

  const first = await installDialog(projectRoot);
  const { catalog, items } = await resolveFixture(["dialog"]);

  const target = join(projectRoot, "behaviors", "dialog.js");
  writeFileSync(target, `${readFileSync(target, "utf8")}\n/* local edit */\n`);

  const conflicts: string[] = [];
  await installBehaviors({
    projectRoot,
    config,
    registry: catalog,
    manifest: first.manifest,
    items,
    onConflict: (file) => {
      conflicts.push(file.target);
      return "keep";
    }
  });

  assert.deepEqual(conflicts, ["behaviors/dialog.js"]);
  assert.match(readFileSync(target, "utf8"), /local edit/);
});

test("legacy manifests keep installed behavior entries", async (t) => {
  const projectRoot = project();
  t.after(() => rmSync(projectRoot, { recursive: true, force: true }));

  const first = await installDialog(projectRoot);
  const legacy = { ...first.manifest };
  delete legacy.behaviorEntries;

  const { source, catalog, items } = await resolveFixture(["button"]);
  await installItems({
    projectRoot,
    config,
    registry: catalog,
    registryUrl: source.url,
    build: catalog.build,
    manifest: legacy,
    items,
    onConflict: () => "keep"
  });

  const manifest = readManifest(projectRoot);
  assert.deepEqual(manifest.behaviorEntries, ["behaviors/dialog.js"]);
  assert.match(
    readFileSync(join(projectRoot, "behaviors", "index.js"), "utf8"),
    /import "\.\/dialog\.js";/
  );
});

test("shared behavior modules install once and appear once in the index", async (t) => {
  const projectRoot = project();
  t.after(() => rmSync(projectRoot, { recursive: true, force: true }));

  const { source, catalog, items } = await resolveFixture([
    "dropdown-menu",
    "menubar"
  ]);
  const result = await installItems({
    projectRoot,
    config,
    registry: catalog,
    registryUrl: source.url,
    build: catalog.build,
    manifest: emptyManifest(),
    items,
    onConflict: () => "keep"
  });

  assert.equal(
    result.behaviorsWritten.filter((file) => file === "behaviors/menu.js").length,
    1
  );
  assert.deepEqual(readManifest(projectRoot).behaviors, [
    "behaviors/core.js",
    "behaviors/menu.js"
  ]);

  const index = readFileSync(join(projectRoot, "behaviors", "index.js"), "utf8");
  assert.equal(index.match(/import "\.\/menu\.js";/g)?.length, 1);
});

test("behaviorDir moves the behavior tree", async (t) => {
  const projectRoot = project();
  t.after(() => rmSync(projectRoot, { recursive: true, force: true }));

  const { source, catalog, items } = await resolveFixture(["dialog"]);
  const customConfig: LosetaConfig = {
    ...config,
    behaviorDir: "src/behaviors"
  };
  await installItems({
    projectRoot,
    config: customConfig,
    registry: catalog,
    registryUrl: source.url,
    build: catalog.build,
    manifest: emptyManifest(),
    items,
    onConflict: () => "keep"
  });

  assert.match(
    readFileSync(join(projectRoot, "src", "behaviors", "index.js"), "utf8"),
    /import "\.\/dialog\.js";/
  );
  assert.throws(() =>
    readFileSync(join(projectRoot, "behaviors", "index.js"), "utf8")
  );
});

import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { installBehaviors, installItems } from "../src/install.js";
import type { LosetaConfig, Manifest } from "../src/types.js";
import { resolveFixture } from "./helpers.js";

const config: LosetaConfig = { cssDir: "styles/loseta", style: "nova" };

function project(): string {
  return mkdtempSync(join(tmpdir(), "loseta-behavior-"));
}

function emptyManifest(): Manifest {
  return { items: [] };
}

function readManifest(projectRoot: string): Manifest {
  return JSON.parse(
    readFileSync(join(projectRoot, ".loseta", "manifest.json"), "utf8")
  ) as Manifest;
}

async function installDialog(
  projectRoot: string,
  options: { manifest?: Manifest; includeBehaviors?: boolean } = {}
) {
  const { source, catalog, items } = await resolveFixture(["dialog"]);
  return installItems({
    projectRoot,
    config,
    registry: catalog,
    registryUrl: source.url,
    build: catalog.build,
    manifest: options.manifest ?? emptyManifest(),
    items,
    includeBehaviors: options.includeBehaviors ?? true,
    onConflict: () => "keep"
  });
}

async function installDrawer(
  projectRoot: string,
  options: { manifest?: Manifest; includeBehaviors?: boolean } = {}
) {
  const { source, catalog, items } = await resolveFixture(["drawer"]);
  return installItems({
    projectRoot,
    config,
    registry: catalog,
    registryUrl: source.url,
    build: catalog.build,
    manifest: options.manifest ?? emptyManifest(),
    items,
    includeBehaviors: options.includeBehaviors ?? true,
    onConflict: () => "keep"
  });
}

test("installing an item writes behavior files and the generated index", async (t) => {
  const projectRoot = project();
  t.after(() => rmSync(projectRoot, { recursive: true, force: true }));

  const result = await installDialog(projectRoot);

  assert.ok(result.written.includes("behaviors/core.js"));
  assert.ok(result.written.includes("behaviors/dialog.js"));
  assert.ok(result.behaviorsWritten.includes("behaviors/dialog.js"));

  const manifest = readManifest(projectRoot);
  assert.deepEqual(manifest.behaviors, [
    "behaviors/core.js",
    "behaviors/dialog.js"
  ]);
  assert.deepEqual(manifest.behaviorEntries, ["behaviors/dialog.js"]);

  const index = readFileSync(join(projectRoot, "behaviors", "index.js"), "utf8");
  assert.match(index, /Generated by loseta/);
  assert.match(index, /import "\.\/dialog\.js";/);
  assert.doesNotMatch(index, /core\.js/);
});

test("drawer installs its swipe entry and supports a CSS-only install", async (t) => {
  const projectRoot = project();
  const cssOnlyRoot = project();
  t.after(() => rmSync(projectRoot, { recursive: true, force: true }));
  t.after(() => rmSync(cssOnlyRoot, { recursive: true, force: true }));

  const result = await installDrawer(projectRoot);
  assert.ok(result.written.includes("behaviors/dialog.js"));
  assert.ok(result.written.includes("behaviors/drawer.js"));
  assert.deepEqual(readManifest(projectRoot).behaviors, [
    "behaviors/core.js",
    "behaviors/dialog.js",
    "behaviors/drawer.js"
  ]);
  assert.deepEqual(readManifest(projectRoot).behaviorEntries, [
    "behaviors/dialog.js",
    "behaviors/drawer.js"
  ]);

  const index = readFileSync(join(projectRoot, "behaviors", "index.js"), "utf8");
  assert.match(index, /import "\.\/dialog\.js";/);
  assert.match(index, /import "\.\/drawer\.js";/);

  const cssOnly = await installDrawer(cssOnlyRoot, { includeBehaviors: false });
  assert.equal(cssOnly.behaviorsWritten.length, 0);
  assert.equal(readManifest(cssOnlyRoot).behaviors?.length ?? 0, 0);
  assert.throws(() =>
    readFileSync(join(cssOnlyRoot, "behaviors", "index.js"), "utf8")
  );
});

